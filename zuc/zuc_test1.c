#include <stdio.h>
#include <stdint.h>
#include <string.h>
#include <gmssl/zuc.h>

#include "../test/test.h"

int main(void)
{

    uint8_t key[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    uint8_t iv[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};

    uint8_t in[16] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f};
    size_t in_len = 16;
    uint8_t out_expected[16] = {0x1b, 0x35, 0xee, 0x3b, 0xdb, 0xdc, 0xb4, 0x8d, 0xc1, 0x01, 0xde, 0xf1, 0x96, 0x7a, 0x2a, 0xae};
    uint8_t out[16] = {0};

    ZUC_STATE state;
    zuc_init(&state, key, iv);
    zuc_encrypt(&state, in, in_len, out);

    print_u8("in", in, in_len);
    print_u8("out", out, in_len);

    if (memcmp(out, out_expected, in_len) == 0)
    {
        printf("test pass\n");
    }
    else
    {
        printf("test failed\n");
    }

    return 0;
}