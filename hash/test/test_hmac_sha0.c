
#include "../hmac_sha0.h"
#include <stdio.h>
#include <string.h>
#include "../../test/test.h"

int main(void)
{
    const uint8_t msg[] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E};
    uint32_t msg_len = 31;
    const uint8_t key[] = {0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x0E, 0x0F, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17, 0x18, 0x19, 0x1A, 0x1B, 0x1C, 0x1D, 0x1E, 0x1F};
    uint32_t key_len = 32;
    const uint8_t mac_expected[20] = {0x7e, 0xc1, 0xd0, 0x66, 0x0b, 0x98, 0x01, 0xaa, 0x16, 0x32, 0x25, 0xa1, 0xa7, 0x47, 0xcc, 0x65, 0xed, 0xa7, 0x19, 0x0a};
    uint8_t mac[20] = {0};

    HMAC_SHA0_CTX ctx;
    hmac_sha0_init(&ctx, key, key_len);
    hmac_sha0_update(&ctx, msg, msg_len);
    hmac_sha0_final(&ctx, mac);

    print_u8("mac", mac, 20);
    if (memcmp(mac, mac_expected, 20) != 0)
    {
        printf("Test failed!\n");
    }
    else
    {
        printf("Test passed!\n");
    }

    return 0;
}